function cekMember() {
    const nama = document.getElementById("nama").value.trim();
    const umur = document.getElementById("umur").value.trim();

    if (nama === "" || umur === "") {
    document.getElementById("warningOverlay").style.display = "flex";
    return;
    }

  // Tampilkan loading
    const loading = document.getElementById("loading");
    const loadingText = document.getElementById("loading-text");

    loading.style.display = "flex";
    loadingText.innerText = "Mencari Kecocokan...";

  // Loading 3 detik
    setTimeout(() => {
    loadingText.innerText = "Menghitung Level Jomok...";
    }, 3000);

  // Loading 6 detik
    setTimeout(() => {
    loadingText.innerText = "Menentukan Stiker...";
    }, 6000);

  // Selesai setelah 9 detik
    setTimeout(() => {
    // Nama + umur dijadikan penentu hasil
    const data = nama.toLowerCase() + umur;

    let angka = 0;

    for (let i = 0; i < data.length; i++) {
      angka = (angka * 31 + data.charCodeAt(i)) >>> 0;
    }

    const index = angka % member.length;
    const hasil = member[index];

    tampilkanHasil(hasil);
    }, 9000);
}

function tutupWarning() {
  const overlay = document.getElementById("warningOverlay");
  const box = overlay.querySelector(".warning-box");
  box.classList.add("closing");
  setTimeout(() => {
    overlay.style.display = "none";
    box.classList.remove("closing");
  }, 400);
}

function previewSemua() {
  const container = document.getElementById("previewSemua");
  container.innerHTML = "";
  member.forEach((hasil, index) => {
    const item = document.createElement("div");
    item.innerHTML = `
    <h3>${index + 1}. ${hasil.nama}</h3>
    <p>${hasil.tipe} - ${hasil.media}</p> ${
    hasil.tipe === "video"
    ? `<video src="${hasil.media}" controls width="200"></video>`
    : `<img src="${hasil.media}" width="200">`}`;
    container.appendChild(item);
  });
}

function tampilkanHasil(hasil) {
    const loading = document.getElementById("loading");
    const resultOverlay = document.getElementById("resultOverlay");
    const mediaBox = document.getElementById("mediaBox");
    const tombol = document.querySelector(".again-btn");

    loading.style.display = "none";

    document.getElementById("namaMember").innerText = hasil.nama;
    document.getElementById("deskripsiMember").innerText = hasil.deskripsi;
    document.getElementById("ucapanMember").innerText = hasil.ucapan;

  // Bersihkan media sebelumnya
    mediaBox.innerHTML = "";

  // =========================
  // KALAU HASILNYA VIDEO
  // =========================

    if (hasil.tipe === "video") {
    const video = document.createElement("video");

    video.src = hasil.media;
    video.controls = true;
    video.autoplay = true;
    video.playsInline = true;

    video.style.width = "100%";
    video.style.height = "100%";
    video.style.objectFit = "cover";

    mediaBox.appendChild(video);

    // Tombol dikunci selama 6 detik
    tombol.disabled = true;
    tombol.innerText = "Tunggu 6 detik...";

    let waktu = 6;

    const timer = setInterval(() => {
    waktu--;

    if (waktu > 0) {
        tombol.innerText = `Tunggu ${waktu} detik...`;
    } else {
        clearInterval(timer);

        tombol.disabled = false;
        tombol.innerText = "CEK LAGI";
    }
    }, 1000);

    // =========================
    // KALAU HASILNYA FOTO
    // =========================
} else {
    const img = document.createElement("img");

    img.src = hasil.media;
    img.alt = hasil.nama;

    mediaBox.appendChild(img);

    // Foto langsung bisa kembali
    tombol.disabled = false;
    tombol.innerText = "CEK LAGI";
}

  // Tampilkan popup
    resultOverlay.style.display = "flex";
}

function tutupHasil() {
    document.getElementById("resultOverlay").style.display = "none";
}

function cekLagi() {
    document.getElementById("resultOverlay").style.display = "none";

    document.getElementById("nama").value = "";
    document.getElementById("umur").value = "";

    window.scrollTo({
    top: 0,
    behavior: "smooth",
    });
}
